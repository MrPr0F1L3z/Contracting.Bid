// Compiles design tokens (src/design/tokens.json) to CSS custom properties.
// Colour and shadow tokens are declared per theme; the first theme is also the :root default.

function resolve(tokens, token, theme, first, depth = 0) {
  const raw = typeof token.value === 'string' ? token.value : (token.value[theme] ?? token.value[first]);
  const alias = /^\{(.+)\}$/.exec(raw ?? '');
  if (!alias) return raw;
  if (depth > 16) throw new Error(`alias chain too deep at ${token.name}`);
  const target = tokens.find((t) => t.name === alias[1]);
  if (!target) throw new Error(`${token.name} aliases missing token ${alias[1]}`);
  return resolve(tokens, target, theme, first, depth + 1);
}

/** tokens.json object → CSS text. */
export function tokensToCss(tokens) {
  const themes = tokens.color.themes.map((t) => t.id);
  const first = themes[0];
  const colors = tokens.color.tokens;
  const shadows = tokens.shadow?.tokens ?? [];
  const out = ['/* GENERATED by scripts/build-tokens.mjs from tokens.json. Do not edit. */'];
  for (const theme of themes) {
    const selector = theme === first ? `:root, [data-theme="${theme}"]` : `[data-theme="${theme}"]`;
    out.push(`${selector} {`);
    for (const t of colors) out.push(`  --${t.name}: ${resolve(colors, t, theme, first)};`);
    for (const t of shadows) out.push(`  --${t.name}: ${typeof t.value === 'string' ? t.value : (t.value[theme] ?? t.value[first])};`);
    out.push('}');
  }
  out.push(':root {');
  for (const family of ['spacing', 'radius']) for (const t of tokens[family]?.tokens ?? []) out.push(`  --${t.name}: ${t.value};`);
  for (const [key, stack] of Object.entries(tokens.type?.families ?? {})) out.push(`  --font-${key}: ${stack};`);
  out.push('}', '');
  return out.join('\n');
}
