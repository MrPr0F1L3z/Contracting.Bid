import vm from 'node:vm';

// Turns the design system's browser bundle (one script that sets window.CB) into an ES module
// the Next.js app can import. Kept as pure functions so the conversion is unit-tested.

const OPEN = /\(function \(\) \{\s*'use strict';\s*var React = window\.React;/;
const CLOSE = /\}\)\(\);\s*$/;

/** Names exported on `window.CB = { A: A, b: b, ... }`. */
export function exportedNames(source) {
  const start = source.indexOf('window.CB = {');
  if (start < 0) throw new Error('bundle does not assign window.CB');
  const end = source.indexOf('};', start);
  if (end < 0) throw new Error('window.CB assignment is not closed');
  const body = source.slice(start + 'window.CB = {'.length, end);
  const pairs = [...body.matchAll(/([A-Za-z_$][\w$]*)\s*:\s*([A-Za-z_$][\w$]*)/g)];
  if (!pairs.length) throw new Error('window.CB exports nothing');
  // Each entry must be `Name: Name`, so the module can export the binding itself.
  const renamed = pairs.find((m) => m[1] !== m[2]);
  if (renamed) throw new Error(`window.CB.${renamed[1]} is not exported under its own name`);
  return [...new Set(pairs.map((m) => m[1]))];
}

/** The bundle as an ES module with a named export per component and helper. */
export function toModule(source) {
  if (!OPEN.test(source)) throw new Error('bundle does not start with the expected wrapper');
  if (!CLOSE.test(source)) throw new Error('bundle does not end with the expected wrapper');
  const names = exportedNames(source);
  const body = source
    .replace(/^\/\* @ds-bundle:.*\*\/\n/, '')
    .replace(OPEN, '')
    .replace(CLOSE, '')
    .replace('window.CB = {', 'const CB = {');
  return [
    "'use client';",
    '// GENERATED by scripts/import-design-bundle.mjs from the Contracting.Bid design system bundle.',
    '// Change components in the design system, then re-import; do not edit this file by hand.',
    "import * as React from 'react';",
    body.trimEnd(),
    '',
    `export { ${names.join(', ')} };`,
    'export default CB;',
    '',
  ].join('\n');
}

const TEST_HEAD = /^[\s\S]*?const CB = global\.window\.CB;\n/;

/** The bundle's node:test suite, rewritten to run under Vitest against the generated module. */
export function toVitest(source) {
  if (!TEST_HEAD.test(source)) throw new Error('test file does not have the expected setup block');
  return [
    '// GENERATED by scripts/import-design-bundle.mjs from the design system\'s own test suite. Do not edit by hand.',
    "import assert from 'node:assert/strict';",
    "import * as React from 'react';",
    "import { renderToStaticMarkup } from 'react-dom/server';",
    "import { test, vi } from 'vitest';",
    "import CB from '../src/design/cb.js';",
    '',
    'const events = [];',
    "vi.stubGlobal('window', { CustomEvent: class { constructor(type, init) { this.type = type; this.detail = init.detail; } }, dispatchEvent: (e) => events.push(e) });",
    source.replace(TEST_HEAD, ''),
  ].join('\n');
}

/**
 * The sample open projects built into the bundle, as plain data. The bundle is a client-side module,
 * so server code cannot import its values; this gives the server the same records as a JSON file.
 * `React` is whatever React the caller has; the bundle only needs it to load.
 */
export function extractSampleListings(source, React) {
  const window = { React };
  vm.runInNewContext(source, { window, Math, Date, Object, Array, String, Number, JSON });
  const leads = window.CB?.sample?.leads;
  if (!Array.isArray(leads) || leads.length === 0) throw new Error('bundle has no sample listings (CB.sample.leads)');
  return JSON.parse(JSON.stringify(leads));
}
